"""Build all official store artifacts and generate the trusted multi-plugin catalog.

First build optional workers and extension UIs, then run this script, rebuild the
base service (which embeds the new pins), and package the base MSI.
"""
from pathlib import Path
import argparse
import hashlib
import json
import struct
import re
import zipfile

parser = argparse.ArgumentParser()
parser.add_argument('--bootstrap', action='store_true', help='Generate compile-only placeholders for new plugins')
args = parser.parse_args()
root = Path(__file__).resolve().parents[2]
capture_files = ['extension.json', 'sb-easy-capture.exe', 'capture/WinDivert.dll', 'capture/WinDivert64.sys',
                 'licenses/WinDivert.txt', 'licenses/libpcap.txt', 'licenses/vue.txt', 'licenses/sbj-grisu2-MIT.txt']
specs = [
    ('capture', '网络包采集（PCAP）', '采集原始网络包用于底层诊断，HTTPS 仍为密文。需要明文请求与响应，请安装 HTTP(S) 抓包。',
     '包含采集驱动。启用后可采集数据包，上传需单独开启。', capture_files),
    ('statistics', '流量统计', '按应用、域名和出口查看历史流量，定位流量消耗。',
     '启用后在本机记录应用、访问域名、出口和字节数。不读取数据包正文，不上传历史记录。',
     ['extension.json', 'sb-easy-statistics.exe', 'licenses/vue.txt', 'licenses/tldts.txt', 'licenses/tldts-core.txt', 'licenses/sbj-grisu2-MIT.txt']),
    ('network-tools', '网络排查', '集中查看活动连接、规则匹配和脱敏日志，排查代理问题。',
     '打开时读取当前连接元数据、规则和脱敏日志。不采集数据包，不保存访问历史。',
     ['extension.json', 'licenses/vue.txt']),
    ('http-debug', 'HTTP(S) 抓包', '由 mitmproxy 驱动，查看明文请求与响应，支持修改、重放和 HAR 导出。',
     '仅在本机运行。安装 CA 证书需单独操作；会话含敏感正文，默认只保存在内存。仅接管选定域名。',
     ['extension.json', 'sb-easy-http-debug.exe', 'licenses/http-debug.txt', 'licenses/vue.txt']),
    ('ip-check', 'IP 检测', '批量检测节点出口 IPv4 / IPv6，在本地查询地区、ASN 及公开机房、VPN、Tor 名单。显示数据来源和日期。',
     '只让出口检测请求经过指定节点，不切换当前代理。向 ipify 请求出口地址，IP 资料在本地公开数据库中查询；不会将出口 IP 发送给资料接口。结果保存在内存，数据库随扩展版本更新。',
     ['extension.json', 'sb-easy-ip-check.exe', 'licenses/ip-check.txt', 'licenses/vue.txt',
      'data/ip-intelligence.sqlite', 'data/manifest.json', 'licenses/ip-data.txt']),
]
def quote(s):
    return json.dumps(s, ensure_ascii=False)
header = ['/* Generated by package-plugins.py. Review release digests before shipping. */',
          '#ifndef SBW_STORE_CATALOG_H', '#define SBW_STORE_CATALOG_H',
          'static const sbw_extension_release releases[]={']
index = []
with zipfile.ZipFile(root/'build/sb-easy-capture-1.0.0-windows-x64.zip') as capture:
    for id, name, description, permissions, names in specs:
        paths = ['extension/'+n for n in names] + ['view/view.js', 'view/view.css']
        if args.bootstrap and id != 'capture':
            data = b''
        else:
            data = bytearray(b'SBECP001')
            for path in paths:
                folder, relative = path.split('/', 1)
                if id == 'capture':
                    content = capture.read(('payload/' if folder == 'extension' else 'ui/')+relative)
                elif folder == 'view':
                    content = (root/f'windows/ui/dist-{id}'/relative).read_bytes()
                elif relative == 'extension.json':
                    content = (root/f'windows/extensions/{id}/extension.json').read_bytes()
                elif relative.startswith('licenses/'):
                    content = (root/'build/windows-release'/relative).read_bytes()
                else:
                    content = (root/f'build/windows-release/extensions/{id}'/relative).read_bytes()
                if folder == 'view' and relative == 'view.js' and re.search(rb'\bprocess\.env\b', content):
                    raise ValueError(f'{id}: browser module contains unresolved Node environment references')
                if not content:
                    raise ValueError(f'Empty file: {id}/{path}')
                data += struct.pack('<I', len(content)) + content
        digest = hashlib.sha256(data).hexdigest()
        filename = f'{id}-1.0.0-{digest[:16]}.sbe'
        if len(data) > 128*1024*1024:
            raise ValueError('Bundle too large')
        if data:
            (root/'build'/filename).write_bytes(data)
        file_list = ','.join('L'+quote(p.replace('/', '\\')) for p in paths)
        header.append('{' + ','.join(quote(v) for v in [id, name, description, permissions, digest]) +
                      ',L'+quote('http://39.108.98.208:51821/assets/store/'+filename) +
                      f',{len(data)},{{{file_list}}},{len(paths)}' + '},')
        index.append(dict(id=id, file=filename, sha256=digest, size=len(data)))
header += ['};', '#endif', '']
(root/'windows/service/store_catalog.h').write_text('\n'.join(header), encoding='utf-8')
if not args.bootstrap:
    (root/'build/store-release-index.json').write_text(json.dumps(index, indent=2), encoding='utf-8')
print(json.dumps(index, indent=2))
