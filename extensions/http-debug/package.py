"""Record Android store pins and collect the Windows plugin's license notices.
Run with the same Python environment used to freeze the engine, after APK builds.
"""
from pathlib import Path
from importlib import metadata
import argparse
import hashlib
import json

root = Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser()
parser.add_argument('--licenses-only', action='store_true')
args = parser.parse_args()
lines = []
for dist in sorted(metadata.distributions(), key=lambda d: d.metadata['Name'].lower()):
    lines.append(f"\n=== {dist.metadata['Name']} {dist.version} ===\n")
    lines.append(f"Home: {dist.metadata.get('Home-page', '')}\nLicense: {dist.metadata.get('License-Expression', dist.metadata.get('License', 'See below'))}\n")
    for file in dist.files or []:
        if any(word in file.name.upper() for word in ('LICENSE', 'COPYING', 'NOTICE')):
            path = dist.locate_file(file)
            if path.is_file() and path.stat().st_size < 1024 * 1024:
                lines.append(path.read_text(encoding='utf-8', errors='replace'))
destination = root/'build/windows-release/licenses/http-debug.txt'
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text('\n'.join(lines), encoding='utf-8')
if args.licenses_only:
    raise SystemExit(0)

items = []
for abi in ('arm64-v8a', 'x86_64'):
    path = root/f'build/httpdebug-android/http-debug-1.0.0-{abi}.apk'
    data = path.read_bytes(); digest = hashlib.sha256(data).hexdigest()
    filename = f'http-debug-1.0.0-{abi}-{digest[:16]}.apk'
    (path.parent/filename).write_bytes(data)
    items.append(dict(abi=abi, filename=filename, sha256=digest, size=len(data)))
source = ['package io.sbeasy.android', '', '// Generated by extensions/http-debug/package.py; immutable, pinned artifacts.',
          'internal object HttpDebugStore {', '    data class Artifact(val url: String, val sha256: String, val size: Long)',
          '    fun artifact(abis: List<String>): Artifact {',
          '        val abi = abis.firstOrNull { it == "arm64-v8a" || it == "x86_64" }']
for item in items:
    source.append(f'        if (abi == "{item["abi"]}") return Artifact("http://39.108.98.208:51821/assets/store/{item["filename"]}", "{item["sha256"]}", {item["size"]}L)')
source += ['        error("此抓包引擎仅支持 ARM64 和 x86_64；基础代理仍支持其他架构")', '    }', '}']
(root/'android/app/src/main/java/io/sbeasy/android/HttpDebugStore.kt').write_text('\n'.join(source)+'\n', encoding='utf-8')
(root/'build/httpdebug-android/store-index.json').write_text(json.dumps(items,indent=2),encoding='utf-8')
print(json.dumps(items,indent=2))
